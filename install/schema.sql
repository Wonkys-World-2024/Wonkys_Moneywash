CREATE TABLE IF NOT EXISTS ww_laundry_machines (
 id VARCHAR(40) PRIMARY KEY, kind VARCHAR(8) NOT NULL,
 x DOUBLE NOT NULL, y DOUBLE NOT NULL, z DOUBLE NOT NULL
);
CREATE TABLE IF NOT EXISTS ww_laundry_batches (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 owner VARCHAR(64) NOT NULL, machine VARCHAR(40) NULL,
 stage VARCHAR(24) NOT NULL, amount INT UNSIGNED NOT NULL,
 payout INT UNSIGNED NOT NULL, ready BIGINT NOT NULL DEFAULT 0,
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY machine_busy (machine), KEY owner_stage (owner, stage)
);

CREATE TABLE IF NOT EXISTS ww_laundry_props (
 id VARCHAR(40) PRIMARY KEY, x DOUBLE NOT NULL, y DOUBLE NOT NULL, z DOUBLE NOT NULL, h DOUBLE NOT NULL
);
CREATE TABLE IF NOT EXISTS ww_laundry_rentals (
 owner VARCHAR(64) PRIMARY KEY, washer VARCHAR(40) NOT NULL UNIQUE, dryer VARCHAR(40) NOT NULL UNIQUE,
 state VARCHAR(16) NOT NULL, fee INT NOT NULL, batch INT UNSIGNED NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ww_laundry_settings (id VARCHAR(32) PRIMARY KEY, value LONGTEXT NOT NULL);
